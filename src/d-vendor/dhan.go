package dvendor

import (
	"algo/src/shared"
	"bytes"
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"net/http"
	"strconv"
	"time"
)

// DhanVendorConfig contains Dhan-specific configuration parameters
type DhanVendorConfig struct {
	VendorConfig
	DhanClientID string // User-specific identification generated by Dhan
}

// DhanDataVendor implements the DataVendor interface for Dhan
type DhanDataVendor struct {
	config    DhanVendorConfig
	client    *http.Client
	isConnect bool
}

// NewDhanDataVendor creates a new instance of the Dhan data vendor
func NewDhanDataVendor(config DhanVendorConfig) *DhanDataVendor {
	return &DhanDataVendor{
		config: config,
		client: &http.Client{
			Timeout: time.Second * 30,
		},
	}
}

// Connect establishes connection with the Dhan data vendor
func (d *DhanDataVendor) Connect(ctx context.Context) error {
	// Validate that configuration parameters have been set
	if d.config.ClientID == "" || d.config.Token == "" || d.config.BaseURL == "" {
		return errors.New("missing required configuration for Dhan data vendor")
	}

	// Validate the token by making a simple API call to get user profile
	req, err := http.NewRequestWithContext(
		ctx,
		"GET",
		fmt.Sprintf("%s/user/profile", d.config.BaseURL),
		nil,
	)
	if err != nil {
		return fmt.Errorf("failed to create request: %w", err)
	}

	d.setupHeaders(req)

	resp, err := d.client.Do(req)
	if err != nil {
		return fmt.Errorf("failed to connect to Dhan: %w", err)
	}
	defer resp.Body.Close()

	if resp.StatusCode != http.StatusOK {
		return fmt.Errorf("failed to authenticate with Dhan, status code: %d", resp.StatusCode)
	}

	d.isConnect = true
	return nil
}

// setupHeaders sets up the common headers required for Dhan API calls
func (d *DhanDataVendor) setupHeaders(req *http.Request) {
	req.Header.Set("Content-Type", "application/json")
	req.Header.Set("access-token", d.config.Token)
}

// GetQuote gets real-time quote for an instrument
func (d *DhanDataVendor) GetQuote(ctx context.Context, instrumentID int32) (*shared.OHLCV, error) {
	if !d.isConnect {
		return nil, errors.New("not connected to Dhan data vendor")
	}

	req, err := http.NewRequestWithContext(
		ctx,
		"GET",
		fmt.Sprintf("%s/market-quote/%d", d.config.BaseURL, instrumentID),
		nil,
	)
	if err != nil {
		return nil, fmt.Errorf("failed to create get quote request: %w", err)
	}

	d.setupHeaders(req)

	resp, err := d.client.Do(req)
	if err != nil {
		return nil, fmt.Errorf("failed to send get quote request: %w", err)
	}
	defer resp.Body.Close()

	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("get quote failed with status code: %d", resp.StatusCode)
	}

	var quoteResp struct {
		LastPrice float64 `json:"lastPrice"`
		Open      float64 `json:"open"`
		High      float64 `json:"high"`
		Low       float64 `json:"low"`
		Close     float64 `json:"close"`
		Volume    int64   `json:"volume"`
	}

	if err := json.NewDecoder(resp.Body).Decode(&quoteResp); err != nil {
		return nil, fmt.Errorf("failed to decode quote response: %w", err)
	}

	return &shared.OHLCV{
		Open:   quoteResp.Open,
		High:   quoteResp.High,
		Low:    quoteResp.Low,
		Close:  quoteResp.LastPrice,
		Volume: quoteResp.Volume,
	}, nil
}

// Subscribe to real-time updates for instruments
func (d *DhanDataVendor) Subscribe(ctx context.Context, instrumentIDs []int32) error {
	if !d.isConnect {
		return errors.New("not connected to Dhan data vendor")
	}

	// Convert int32 slice to string slice for API
	instrumentIDStrs := make([]string, len(instrumentIDs))
	for i, id := range instrumentIDs {
		instrumentIDStrs[i] = strconv.FormatInt(int64(id), 10)
	}

	subscriptionData := map[string]interface{}{
		"securityIds": instrumentIDStrs,
	}

	jsonData, err := json.Marshal(subscriptionData)
	if err != nil {
		return fmt.Errorf("failed to marshal subscription data: %w", err)
	}

	req, err := http.NewRequestWithContext(
		ctx,
		"POST",
		fmt.Sprintf("%s/live-market-feed", d.config.BaseURL),
		bytes.NewBuffer(jsonData),
	)
	if err != nil {
		return fmt.Errorf("failed to create subscription request: %w", err)
	}

	d.setupHeaders(req)

	resp, err := d.client.Do(req)
	if err != nil {
		return fmt.Errorf("failed to send subscription request: %w", err)
	}
	defer resp.Body.Close()

	if resp.StatusCode != http.StatusOK {
		return fmt.Errorf("subscription failed with status code: %d", resp.StatusCode)
	}

	return nil
}

