package repository

import (
	"context"
	"time"

	"algo/internal/modules/marketplace/domain/model"

	"github.com/google/uuid"
)

// TransactionRepository defines the interface for marketplace transaction repository
type TransactionRepository interface {
	// Create creates a new transaction
	Create(ctx context.Context, transaction *model.Transaction) error

	// FindByID returns a transaction by its ID
	FindByID(ctx context.Context, id uuid.UUID) (*model.Transaction, error)

	// FindBySubscriptionID returns all transactions for a subscription
	FindBySubscriptionID(ctx context.Context, subscriptionID uuid.UUID) ([]*model.Transaction, error)

	// FindByUserID returns all transactions for a user
	FindByUserID(ctx context.Context, userID uuid.UUID) ([]*model.Transaction, error)

	// FindBySellerID returns all transactions for a seller
	FindBySellerID(ctx context.Context, sellerID uuid.UUID) ([]*model.Transaction, error)

	// Update updates a transaction
	Update(ctx context.Context, transaction *model.Transaction) error

	// GetRevenueBySeller gets the revenue generated by a seller
	GetRevenueBySeller(ctx context.Context, sellerID uuid.UUID, startDate, endDate time.Time) (float64, error)
}
