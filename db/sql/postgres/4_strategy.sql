-- Strategy Management Tables
CREATE TABLE IF NOT EXISTS strategy (
    id UUID DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL REFERENCES "user"(id) ON DELETE CASCADE,
    name VARCHAR NOT NULL,
    description VARCHAR,
    position_type direction NOT NULL,
    instruments INT[] NOT NULL,
    chart_type chart_type NOT NULL,
    chart_timeframe chart_timeframe NOT NULL,
    trade_type trade_type NOT NULL,
    qty INT NOT NULL,
    entry_expression TEXT NOT NULL,
    exit_expression TEXT,
    target_profit DECIMAL(18, 8) NOT NULL,
    target_profit_type value_type NOT NULL,
    stop_loss DECIMAL(18, 8) NOT NULL,
    stop_loss_type value_type NOT NULL,
    trailing_stop_loss DECIMAL(18, 8),
    trailing_stop_loss_type value_type,
    exit_type VARCHAR,
    capital DECIMAL(18, 8) NOT NULL,
    max_allocation DECIMAL(18, 8) NOT NULL,
    max_trades INT,
    entry_start_time TIME,
    entry_end_time TIME,
    start_date DATE,
    end_date DATE,
    created_at TIMESTAMP DEFAULT now(),
    updated_at TIMESTAMP DEFAULT now(),
    is_active BOOLEAN DEFAULT true,
    PRIMARY KEY (id)
);
