-- Strategy Management Tables
CREATE TABLE IF NOT EXISTS strategy (
    id UUID DEFAULT gen_random_uuid(),
    user_id UUID REFERENCES "user"(id) ON DELETE CASCADE,
    name VARCHAR,
    description VARCHAR,
    position_type direction NOT NULL,
    instruments INT[],
    chart_type chart_type,
    chart_timeframe chart_timeframe,
    trade_type trade_type,
    qty INT,
    entry_expression TEXT,
    exit_expression TEXT,
    target_profit DECIMAL(18, 8),
    target_profit_type value_type,
    stop_loss DECIMAL(18, 8),
    stop_loss_type value_type,
    trailing_stop_loss DECIMAL(18, 8),
    trailing_stop_loss_type value_type,
    exit_type VARCHAR,
    capital DECIMAL(18, 8),
    max_trades INT,
    entry_start_time TIMESTAMP,
    entry_end_time TIMESTAMP,
    start_date DATE,
    end_date DATE,
    created_at TIMESTAMP DEFAULT now(),
    updated_at TIMESTAMP DEFAULT now(),
    is_active BOOLEAN DEFAULT true,
    PRIMARY KEY (id)
);
